function resolveIconName(name: string) {
    const parts = name.trim().split(/\s+/).filter(Boolean);
    const iconClass = [...parts].reverse().find((part) => {
        return part.startsWith('fa-') && !['fa-solid', 'fa-regular', 'fa-brands'].includes(part);
    });

    return (iconClass ?? name).replace(/^fa-/, '');
}

export function Icon(props: { name: string; class?: string; title?: string; size?: string }) {
    const definition = createMemo(() => icons[resolveIconName(props.name)]);

    return (
        <Show when={definition()} keyed>
            {(current) => (
                <svg
                    class={props.class ? `svg-icon ${props.class}` : 'svg-icon'}
                    viewBox={current.viewBox}
                    width={props.size ?? '1em'}
                    height={props.size ?? '1em'}
                    role={props.title ? 'img' : undefined}
                    aria-hidden={props.title ? undefined : 'true'}
                    style={iconStyle}
                >
                    {props.title ? <title>{props.title}</title> : null}
                    <path fill="currentColor" d={current.path} />
                </svg>
            )}
        </Show>
    );
}
